 assert.match(await page.locator('#template-list').innerText(),/Shared greeting/);
 assert.match(await page.locator('#template-list .pending').innerText(),/Unapplied/);
 assert.match(await page.locator('#length').innerText(),/18 \/ 335 characters/);
 await page.getByLabel('Apply to @Friend · Default',{exact:true}).check();
 await mkdir('browser-temp',{recursive:true});
 await page.screenshot({path:'browser-temp/editor-pending.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Multi-account editor fits a narrow screen');
 await page.setViewportSize({width:1440,height:1000});
 await page.getByRole('button',{name:'Apply changes',exact:true}).click();
 assert.equal(await page.locator('#template-list .pending').count(),0);
 const downloadWait=page.waitForEvent('download');await page.getByRole('button',{name:'Download Lua',exact:true}).click();
 const text=await readFile(await(await downloadWait).path(),'utf8'),doc=parseSavedVariables(text);
 const writer=doc.Default['@Writer'].$AccountWide,friend=doc.Default['@Friend'].$AccountWide;
 const first=Object.values(writer.settings.welcomeMessages).find(e=>e.title==='Shared greeting');
 const second=Object.values(friend.settings.welcomeMessages).find(e=>e.title==='Shared greeting');
 assert.equal(first.message,'Line one\n\nLine two');assert.equal(first.webTemplateId,second.webTemplateId);assert.notEqual(first.id,second.id);
 assert.equal(writer.records[1].private,'keep');assert.equal(friend.settings.welcomeMessages[1].useCount,17);
 assert.equal(Object.keys(doc.Default['@Third'].$AccountWide.settings.welcomeMessages).length,0);
 assert.match(text,/Line one\\n\\nLine two/);assert.doesNotMatch(text,/\\010|\\013/);
 // Every input path must respect characters, including non-ASCII text and insertion.
 await page.getByLabel('Message text').fill('é'.repeat(336));
 assert.equal([...(await page.getByLabel('Message text').inputValue())].length,335);
 await page.getByLabel('Message text').press('End');await page.keyboard.insertText('x');
 assert.equal([...(await page.getByLabel('Message text').inputValue())].length,335);
 await page.getByLabel('Message text').fill('A'.repeat(333)+'BC');
 await page.getByLabel('Message text').evaluate(field=>{field.setSelectionRange(333,334);field.focus();});
 await page.keyboard.insertText('XYZ');
 assert.equal(await page.getByLabel('Message text').inputValue(),'A'.repeat(333)+'XC');
 await page.getByRole('button',{name:'+ {name}',exact:true}).click();
 assert.equal([...(await page.getByLabel('Message text').inputValue())].length,335);
 await page.getByLabel('Message text').fill('A'.repeat(333));
 await page.getByRole('button',{name:'+ {name}',exact:true}).click();
 assert.equal(await page.getByLabel('Message text').inputValue(),'A'.repeat(333));
 await page.getByRole('button',{name:'Discard draft',exact:true}).click();
 await page.getByRole('tab',{name:/Welcome emails/}).click();
 await page.getByLabel('Email subject').fill('S'.repeat(38));
 assert.equal((await page.getByLabel('Email subject').inputValue()).length,37);
 await page.getByLabel('Email body').fill('B'.repeat(681));
 assert.equal((await page.getByLabel('Email body').inputValue()).length,680);
 assert.match(await page.locator('#subject-length').innerText(),/37 \/ 37/);
 await page.getByLabel('Email subject').fill('Shared email');
 await page.getByLabel('Email body').fill('First paragraph\n\nSecond paragraph');
 await page.getByLabel('Apply to @Friend · Default',{exact:true}).check();
 await page.getByRole('button',{name:'Apply changes',exact:true}).click();
 const mailDownload=page.waitForEvent('download');await page.getByRole('button',{name:'Download Lua',exact:true}).click();
 const mailDoc=parseSavedVariables(await readFile(await(await mailDownload).path(),'utf8'));
 const mail=mailDoc.Default['@Friend'].$AccountWide.settings.welcomeEmails[1];
 assert.equal(mail.subject,'Shared email');assert.equal(mail.id,12);assert.equal(mail.useCount,22);assert.equal(mail.lastUsed,123);
 assert.equal(mailDoc.Default['@Writer'].$AccountWide.settings.captureApplicationData,false);
 assert.equal(mailDoc.Default['@Friend'].$AccountWide.settings.captureApplicationData,true);
 // Selecting accounts alone can copy an already-applied template without text edits.
 await page.getByLabel('Apply to @Third · Default',{exact:true}).check();
 await page.getByRole('button',{name:'Apply changes',exact:true}).click();
 const copyDownload=page.waitForEvent('download');await page.getByRole('button',{name:'Download Lua',exact:true}).click();
 const copied=parseSavedVariables(await readFile(await(await copyDownload).path(),'utf8'));
